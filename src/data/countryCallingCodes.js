export function getCountryByCode(code) {
  if (!code) return null;
  return COUNTRIES.find(c => c.code.toUpperCase() === code.toUpperCase()) || null;
}

export function getCountryByDialCode(dialCode) {
  if (!dialCode) return null;
  const clean = dialCode.trim();
  return COUNTRIES.find(c => c.dialCode === clean) || null;
}
